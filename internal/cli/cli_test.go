package cli_test

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	"github.com/RogueConsultingDev/onyx/internal/cli"
)

const (
	messy     = "package p\nvar  x=1\n"
	formatted = "package p\n\nvar x = 1\n"
)

type result struct {
	status int
	stdout string
	stderr string
}

func run(t *testing.T, stdin string, args ...string) result {
	t.Helper()

	var stdout, stderr bytes.Buffer

	status := cli.Run(args, strings.NewReader(stdin), &stdout, &stderr)

	return result{status, stdout.String(), stderr.String()}
}

func write(t *testing.T, path, content string) {
	t.Helper()

	require.NoError(t, os.MkdirAll(filepath.Dir(path), 0o750))
	require.NoError(t, os.WriteFile(path, []byte(content), 0o600))
}

func read(t *testing.T, path string) string {
	t.Helper()

	content, err := os.ReadFile(path)
	require.NoError(t, err)

	return string(content)
}

func TestRewritesFilesInPlace(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	path := filepath.Join(dir, "a.go")
	write(t, path, messy)

	got := run(t, "", path)

	assert.Equal(t, cli.ExitOK, got.status)
	assert.Contains(t, got.stderr, "reformatted "+path)
	assert.Equal(t, formatted, read(t, path))

	got = run(t, "", path)

	assert.Equal(t, cli.ExitOK, got.status)
	assert.Empty(t, got.stderr)
}

func TestCheck(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	path := filepath.Join(dir, "a.go")
	write(t, path, messy)

	got := run(t, "", "--check", path)

	assert.Equal(t, cli.ExitChanges, got.status)
	assert.Contains(t, got.stderr, "would reformat "+path)
	assert.Equal(t, messy, read(t, path))

	write(t, path, formatted)

	assert.Equal(t, cli.ExitOK, run(t, "", "--check", path).status)
}

func TestDiff(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	path := filepath.Join(dir, "a.go")
	write(t, path, messy)

	got := run(t, "", "--diff", path)

	assert.Equal(t, cli.ExitOK, got.status)
	assert.Contains(t, got.stdout, "-var  x=1")
	assert.Contains(t, got.stdout, "+var x = 1")
	assert.Equal(t, messy, read(t, path))

	got = run(t, "", "--diff", "--check", path)

	assert.Equal(t, cli.ExitChanges, got.status)
}

func TestStdin(t *testing.T) {
	t.Parallel()

	got := run(t, messy, "-")

	assert.Equal(t, cli.ExitOK, got.status)
	assert.Equal(t, formatted, got.stdout)

	got = run(t, messy, "--check", "-")

	assert.Equal(t, cli.ExitChanges, got.status)
	assert.Empty(t, got.stdout)

	got = run(t, messy, "--diff", "-")

	assert.Equal(t, cli.ExitOK, got.status)
	assert.Contains(t, got.stdout, "+var x = 1")

	got = run(t, formatted, "--check", "-")

	assert.Equal(t, cli.ExitOK, got.status)
}

func TestWalksDirectories(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	write(t, filepath.Join(dir, "a.go"), messy)
	write(t, filepath.Join(dir, "sub", "b.go"), messy)
	write(t, filepath.Join(dir, "vendor", "c.go"), messy)
	write(t, filepath.Join(dir, ".hidden", "d.go"), messy)
	write(t, filepath.Join(dir, "notes.txt"), "not go")
	write(t, filepath.Join(dir, "gen.go"), "// Code generated by hand. DO NOT EDIT.\n\n"+messy)

	got := run(t, "", dir)

	assert.Equal(t, cli.ExitOK, got.status, got.stderr)
	assert.Equal(t, formatted, read(t, filepath.Join(dir, "a.go")))
	assert.Equal(t, formatted, read(t, filepath.Join(dir, "sub", "b.go")))
	assert.Equal(t, messy, read(t, filepath.Join(dir, "vendor", "c.go")))
	assert.Equal(t, messy, read(t, filepath.Join(dir, ".hidden", "d.go")))
	assert.Contains(t, read(t, filepath.Join(dir, "gen.go")), "var  x=1")
}

func TestSettingsFlagsAndConfig(t *testing.T) {
	t.Parallel()

	const call = "package p\n\nvar x = f(aaaaaaaaaa, bbbbbbbbbb)\n"

	dir := t.TempDir()
	path := filepath.Join(dir, "a.go")
	write(t, path, call)

	got := run(t, "", "--check", "--line-length=20", path)
	assert.Equal(t, cli.ExitChanges, got.status)

	got = run(t, "", "--check", "--tab-width=2", "--magic-trailing-comma=false", path)
	assert.Equal(t, cli.ExitOK, got.status, got.stderr)

	write(t, filepath.Join(dir, ".onyx.toml"), "line-length = 20\n")

	got = run(t, "", "--check", path)
	assert.Equal(t, cli.ExitChanges, got.status)

	other := filepath.Join(t.TempDir(), "other.toml")
	write(t, other, "line-length = 200\n")

	got = run(t, "", "--check", "--config", other, path)
	assert.Equal(t, cli.ExitOK, got.status, got.stderr)

	got = run(t, "", "--check", "--config", filepath.Join(dir, "missing.toml"), path)
	assert.Equal(t, cli.ExitError, got.status)
	assert.Contains(t, got.stderr, "error resolving settings")
}

