func TestErrors(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	broken := filepath.Join(dir, "broken.go")
	write(t, broken, "package")

	tests := map[string]struct {
		stdin string
		args  []string
		want  string
	}{
		"missing path":          {"", []string{filepath.Join(dir, "none.go")}, "error reading"},
		"syntax error":          {"", []string{broken}, "broken.go"},
		"syntax error in stdin": {"package", []string{"-"}, "<stdin>"},
		"unsupported": {
			"package p\nvar x = a + /* c */ b\n",
			[]string{"-"},
			"unsupported construct",
		},
	}

	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			got := run(t, test.stdin, paths(test.args...))

			assert.Equal(t, cli.ExitError, got.status)
			assert.Contains(t, got.stderr, test.want)
		})
	}
}

func TestParsePositive(t *testing.T) {
	t.Parallel()

	got, err := cli.ParsePositive("7")
	require.NoError(t, err)
	assert.Equal(t, 7, got)

	_, err = cli.ParsePositive("x")
	require.ErrorContains(t, err, "invalid number")

	_, err = cli.ParsePositive("0")
	require.ErrorContains(t, err, "not positive")
}

func TestUnreadableFiles(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	path := filepath.Join(dir, "a.go")
	write(t, path, messy)
	require.NoError(t, os.Chmod(path, 0o000))

	t.Cleanup(func() { _ = os.Chmod(path, 0o600) })

	got := run(t, "", paths(path))
	assert.Equal(t, cli.ExitError, got.status)

	got = run(t, "", paths(dir))
	assert.Equal(t, cli.ExitError, got.status)
}

type failingReader struct{}

func (failingReader) Read([]byte) (int, error) { return 0, os.ErrClosed }

type failingWriter struct{}

func (failingWriter) Write([]byte) (int, error) { return 0, os.ErrClosed }

func TestIOFailures(t *testing.T) {
	t.Parallel()

	var stderr bytes.Buffer

	status := cli.Run(paths("-"), failingReader{}, &bytes.Buffer{}, &stderr)
	assert.Equal(t, cli.ExitError, status)
	assert.Contains(t, stderr.String(), "error reading standard input")

	for _, options := range []cli.Options{{Diff: true, Paths: []string{"-"}}, paths("-")} {
		stderr.Reset()

		status = cli.Run(options, strings.NewReader(messy), failingWriter{}, &stderr)
		assert.Equal(t, cli.ExitError, status)
	}

	dir := t.TempDir()
	write(t, filepath.Join(dir, "a.go"), messy)

	status = cli.Run(
		cli.Options{Diff: true, Paths: []string{dir}},
		strings.NewReader(""),
		failingWriter{},
		&stderr,
	)
	assert.Equal(t, cli.ExitError, status)

	status = cli.Run(
		paths(filepath.Join(dir, "missing")),
		strings.NewReader(""),
		&bytes.Buffer{},
		&stderr,
	)
	assert.Equal(t, cli.ExitError, status)
}

