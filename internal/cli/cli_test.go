func TestErrors(t *testing.T) {
	t.Parallel()

	dir := t.TempDir()
	broken := filepath.Join(dir, "broken.go")
	write(t, broken, "package")

	tests := map[string]struct {
		stdin string
		args  []string
		want  string
	}{
		"no paths":            {"", nil, "no paths given"},
		"unknown flag":        {"", []string{"--nope"}, "flag provided but not defined"},
		"bad number":          {"", []string{"--line-length=x", "-"}, "invalid number"},
		"non positive number": {"", []string{"--tab-width=0", "-"}, "not positive"},
		"bad boolean": {
			"",
			[]string{"--magic-trailing-comma=maybe", "-"},
			"invalid boolean value",
		},
		"missing path":          {"", []string{filepath.Join(dir, "none.go")}, "error reading"},
		"syntax error":          {"", []string{broken}, "broken.go"},
		"syntax error in stdin": {"package", []string{"-"}, "<stdin>"},
		"unsupported": {
			"package p\nvar x = a + /* c */ b\n",
			[]string{"-"},
			"unsupported construct",
		},
	}

	for name, test := range tests {
		t.Run(name, func(t *testing.T) {
			t.Parallel()

			got := run(t, test.stdin, test.args...)

			assert.Equal(t, cli.ExitError, got.status)
			assert.Contains(t, got.stderr, test.want)
		})
	}
}

